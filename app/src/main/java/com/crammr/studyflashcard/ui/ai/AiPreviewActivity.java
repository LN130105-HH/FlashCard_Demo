package com.crammr.studyflashcard.ui.ai;

import android.content.Intent;
import android.os.Bundle;
import android.text.TextUtils;
import android.widget.Toast;

import androidx.appcompat.app.AppCompatActivity;
import androidx.recyclerview.widget.LinearLayoutManager;

import com.crammr.studyflashcard.data.local.entity.Flashcard;
import com.crammr.studyflashcard.data.local.entity.FlashcardCollection;
import com.crammr.studyflashcard.data.repository.FlashcardRepository;
import com.crammr.studyflashcard.databinding.ActivityAiPreviewBinding;
import com.crammr.studyflashcard.ui.adapter.PreviewCardAdapter;
import com.crammr.studyflashcard.ui.library.CollectionDetailActivity;

import java.util.ArrayList;
import java.util.List;

public class AiPreviewActivity extends AppCompatActivity {

    private ActivityAiPreviewBinding binding;
    private FlashcardRepository repository;
    private PreviewCardAdapter adapter;
    private List<Flashcard> cards = new ArrayList<>();

    @Override
    protected void onCreate(Bundle savedInstanceState) {
        super.onCreate(savedInstanceState);
        binding = ActivityAiPreviewBinding.inflate(getLayoutInflater());
        setContentView(binding.getRoot());

        repository = new FlashcardRepository(getApplication());

        String sourceName = getIntent().getStringExtra("source_name");
        if (sourceName != null && !sourceName.isEmpty()) {
            binding.etTargetCollectionName.setText(sourceName);
        }

        List<Flashcard> passedCards = (List<Flashcard>) getIntent().getSerializableExtra("generated_cards");
        if (passedCards != null) {
            cards = passedCards;
        }

        binding.toolbarAiPreview.setNavigationOnClickListener(v -> finish());

        adapter = new PreviewCardAdapter(cards);
        binding.rvPreviewCards.setLayoutManager(new LinearLayoutManager(this));
        binding.rvPreviewCards.setAdapter(adapter);

        updateCardCount();

        binding.btnAddMorePreviewCard.setOnClickListener(v -> {
            adapter.addCard(new Flashcard(0, "New Question", "New Answer", "Added manually"));
            binding.rvPreviewCards.smoothScrollToPosition(adapter.getItemCount() - 1);
            updateCardCount();
        });

        binding.btnSavePreviewToLibrary.setOnClickListener(v -> saveDeck());
    }

    private void updateCardCount() {
        binding.tvPreviewCardCount.setText("Generated Cards (" + adapter.getItemCount() + ")");
    }

    private void saveDeck() {
        String deckName = binding.etTargetCollectionName.getText() != null
                ? binding.etTargetCollectionName.getText().toString().trim() : "";

        if (TextUtils.isEmpty(deckName)) {
            binding.etTargetCollectionName.setError("Deck name is required");
            binding.etTargetCollectionName.requestFocus();
            return;
        }

        List<Flashcard> finalCards = adapter.getCards();
        if (finalCards.isEmpty()) {
            Toast.makeText(this, "Deck cannot be empty", Toast.LENGTH_SHORT).show();
            return;
        }

        FlashcardCollection newCol = new FlashcardCollection(1, 1, deckName, "Generated by Crammr AI.");
        newCol.setCardCount(finalCards.size());

        repository.insertCollection(newCol, collectionId -> {
            for (Flashcard c : finalCards) {
                c.setCollectionId(collectionId);
            }
            repository.insertFlashcards(finalCards, collectionId);

            runOnUiThread(() -> {
                Toast.makeText(this, "Deck saved to Library! (" + finalCards.size() + " cards)", Toast.LENGTH_SHORT).show();
                Intent intent = new Intent(this, CollectionDetailActivity.class);
                intent.putExtra("collection_id", collectionId);
                startActivity(intent);
                finish();
            });
        });
    }
}
