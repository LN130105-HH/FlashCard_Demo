package com.crammr.studyflashcard.service;

import com.crammr.studyflashcard.data.local.entity.Flashcard;
import com.crammr.studyflashcard.ui.study.QuizQuestionModel;

import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class AiGeneratorEngine {

    /**
     * Generates flashcard items from raw text / prompt.
     */
    public static List<Flashcard> generateFlashcardsFromText(String rawText, long collectionId) {
        List<Flashcard> results = new ArrayList<>();
        if (rawText == null || rawText.trim().isEmpty()) {
            return results;
        }

        // Try extracting based on "Q: ... A: ..." or "Question: ... Answer: ..." or colon separators
        String[] lines = rawText.split("\n");
        String currentQuestion = null;
        StringBuilder currentAnswer = new StringBuilder();

        Pattern qaPattern = Pattern.compile("^(?:Q\\d*|Question\\d*|\\d+[\\.\\)]):?\\s*(.*)", Pattern.CASE_INSENSITIVE);
        Pattern ansPattern = Pattern.compile("^(?:A\\d*|Answer\\d*):?\\s*(.*)", Pattern.CASE_INSENSITIVE);

        for (String line : lines) {
            String trimmed = line.trim();
            if (trimmed.isEmpty()) continue;

            Matcher qMatcher = qaPattern.matcher(trimmed);
            Matcher aMatcher = ansPattern.matcher(trimmed);

            if (qMatcher.find()) {
                if (currentQuestion != null && currentAnswer.length() > 0) {
                    results.add(new Flashcard(collectionId, currentQuestion, currentAnswer.toString().trim(), "Extracted from source notes."));
                    currentAnswer = new StringBuilder();
                }
                currentQuestion = qMatcher.group(1);
            } else if (aMatcher.find()) {
                currentAnswer.append(aMatcher.group(1)).append(" ");
            } else if (trimmed.contains(" - ") || trimmed.contains(" — ") || trimmed.contains(": ")) {
                String[] parts = trimmed.contains(" - ") ? trimmed.split(" - ", 2)
                        : (trimmed.contains(" — ") ? trimmed.split(" — ", 2) : trimmed.split(": ", 2));
                if (parts.length == 2 && parts[0].length() > 2 && parts[1].length() > 2) {
                    if (currentQuestion != null && currentAnswer.length() > 0) {
                        results.add(new Flashcard(collectionId, currentQuestion, currentAnswer.toString().trim(), "Extracted from source notes."));
                        currentQuestion = null;
                        currentAnswer = new StringBuilder();
                    }
                    results.add(new Flashcard(collectionId, parts[0].trim(), parts[1].trim(), "Generated by Crammr AI."));
                } else if (currentQuestion != null) {
                    currentAnswer.append(trimmed).append(" ");
                }
            } else if (currentQuestion != null) {
                currentAnswer.append(trimmed).append(" ");
            }
        }

        if (currentQuestion != null && currentAnswer.length() > 0) {
            results.add(new Flashcard(collectionId, currentQuestion, currentAnswer.toString().trim(), "Extracted from notes."));
        }

        // If no structured pattern matched, generate smart semantic chunk cards
        if (results.isEmpty()) {
            String[] sentences = rawText.split("\\. |\\?\\s|\\!\\s");
            for (int i = 0; i < sentences.length && results.size() < 10; i++) {
                String s = sentences[i].trim();
                if (s.length() > 25) {
                    String q = "What is the key takeaway regarding: " + getSummaryHeading(s) + "?";
                    results.add(new Flashcard(collectionId, q, s, "Key concept extracted from document."));
                }
            }
        }

        // If still empty (e.g. short prompt), provide contextual AI educational cards
        if (results.isEmpty()) {
            results.add(new Flashcard(collectionId,
                    "Core Definition: " + (rawText.length() > 30 ? rawText.substring(0, 30) + "..." : rawText),
                    rawText,
                    "Generated based on your study input."));
        }

        return results;
    }

    /**
     * Generates Quiz Multiple Choice Questions from text.
     */
    public static List<QuizQuestionModel> generateQuizFromCards(List<Flashcard> cards, int limit) {
        List<QuizQuestionModel> quizList = new ArrayList<>();
        if (cards == null || cards.isEmpty()) return quizList;

        int total = Math.min(cards.size(), limit <= 0 ? cards.size() : limit);

        for (int i = 0; i < total; i++) {
            Flashcard card = cards.get(i);
            String question = card.getQuestion();
            String correctAnswer = card.getAnswer();

            List<String> options = new ArrayList<>();
            options.add(correctAnswer);

            // Add 3 plausible distractor answers from other cards or templates
            for (int j = 0; j < cards.size() && options.size() < 4; j++) {
                if (j != i) {
                    String distractor = cards.get(j).getAnswer();
                    if (!options.contains(distractor)) {
                        options.add(distractor);
                    }
                }
            }

            // Fill standard distractors if card pool is small
            if (options.size() < 4) {
                options.add("None of the above options are correct.");
            }
            if (options.size() < 4) {
                options.add("It only applies under specific edge conditions.");
            }
            if (options.size() < 4) {
                options.add("Both theoretical and empirical values differ.");
            }

            // Shuffle options
            java.util.Collections.shuffle(options);
            int correctIndex = options.indexOf(correctAnswer);

            quizList.add(new QuizQuestionModel(
                    question,
                    options,
                    correctIndex,
                    card.getExplanation() != null ? card.getExplanation() : "Correct answer: " + correctAnswer
            ));
        }

        return quizList;
    }

    private static String getSummaryHeading(String sentence) {
        String[] words = sentence.split(" ");
        int count = Math.min(words.length, 5);
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < count; i++) {
            sb.append(words[i]).append(" ");
        }
        return sb.toString().trim();
    }
}
